#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

int main() {
    setlocale(LC_CTYPE, "RUS");

    // Шаг 1: Объявление переменных
    int a, b, c;
    int ideal;

    // Шаг 2: Ввод параметров кислотности
    printf("Введите три параметра кислотности (A B C): ");
    scanf("%d %d %d", &a, &b, &c);

    // Шаг 3: Проверка условия идеальности
    // Лунка идеальна, если все три параметра кратны 3
    ideal = (a % 3 == 0) && (b % 3 == 0) && (c % 3 == 0);

    // Шаг 4: Вывод результата
    printf("\nРЕЗУЛЬТАТ ПРОВЕРКИ ЛУНКИ\n");
    printf("************************************\n");
    printf("Параметры кислотности: A=%d, B=%d, C=%d\n", a, b, c);
    printf("************************************\n");
    printf("Доступ разрешен (1 - да, 0 - нет): %d\n", ideal);

    return 0;
}